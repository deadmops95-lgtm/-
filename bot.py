@bot.message_handler(commands=["start"])
def send_welcome(message):
  markup = types.InlineKeyboardMarkup(row_width=2)
  buttons = [
      types.InlineKeyboardButton(sign, callback_data=f"sign_{sign}")
      for sign in ZODIAC_SIGNS
  ]
  markup.add(*buttons)

  bot.send_message(
      message.chat.id,
      "☠️ **Честный гороскоп без цензуры запущен!**\n\nНикаких нейросетей и"
      " зависаний. Выбирай свой знак и получай порцию правды:",
      reply_markup=markup,
      parse_mode="Markdown",
  )


@bot.callback_query_handler(func=lambda call: call.data.startswith("sign_"))
def callback_inline(call):
  sign = call.data.split("_")[1]

  # Выбираем случайную фразу из нашей большой базы для этого знака
  sign_predictions = SARCASTIC_HOROSCOPES.get(
      sign, ["Сегодня всё плохо, но ты привык."]
  )
  prediction = random.choice(sign_predictions)

  bot.answer_callback_query(call.id)
  bot.send_message(
      call.message.chat.id,
      f"🔥 **Гороскоп для {sign}:**\n\n{prediction}\n\n*Хватит ныть, жми"
      " /start снова.*",
      parse_mode="Markdown",
  )


